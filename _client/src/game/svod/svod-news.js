/** Вкладка «Новости» — в проекте нет никакого серверного источника новостей (ни JSON, ни
 * контроллера), поэтому это честная заглушка, а не подключение к несуществующему бэкенду.
 * Когда появится реальный источник (например server/json/news.json) — заменить содержимое
 * _buildNewsPanel на реальную загрузку, разметка панели уже готова.
 *
 * 19.09.2026 (по прямому указанию): у панели появился настоящий фон (задний фон новости.png,
 * 851×546 — ровно PANEL_W×PANEL_H, вставляется в нативном размере без scale) вместо серой
 * Graphics-заглушки.
 *
 * 21.09.2026 (по прямому указанию) — тизеры «Ящик» и «Скряга» УБРАНЫ: Скряга ещё не готова к
 * бета-тесту (см. BETA_LOCKED в hapuga.php) — анонсировать её в новостях преждевременно, а
 * тизер ящика тоже решили больше не показывать. Файлы 'новости ящик.png'/'новости скряга.png'
 * остаются на диске (сверены по MD5 с исходниками пользователя вкладыш.png/Слой 241.png) —
 * удаление с продового сервера делается отдельно, по команде «деплой» (Правило №4).
 */
export function attachSvodNews(proto){
    const IMG = './images/';
    const PANEL_X = 284, PANEL_Y = 65, PANEL_W = 851, PANEL_H = 546;

    proto._buildNewsPanel = function(){
        const win = new PIXI.Container();
        win.visible = false;

        const bg = new PIXI.Sprite(PIXI.Texture.from(IMG + 'задний фон новости.png'));
        bg.x = PANEL_X; bg.y = PANEL_Y;
        win.addChild(bg);

        return win;
    };
}
