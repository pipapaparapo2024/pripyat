/** Общая логика "схлопывания" тиров одного достижения в одну тему (17.09.2026, по прямому
 * указанию) — используется в ДВУХ местах: achievements.js._checkAll() (чтобы при пересечении
 * сразу нескольких порогов одной темы показывался только попап САМОГО высокого) и
 * svod/svod-achievements.js (панель «Мои достижения» — одна карточка на тему).
 *
 * Схлопывать можно только настоящие "уровни одной темы" (урон/автоматы/тушёнка и т.п.) — НЕ
 * категории, где каждый пункт сам по себе отдельное достижение: по боссу (kill/solo/fast), по
 * локации (zone_clear), по типу заначки (stash), комбинации карт/покера/рулетки.
 */

// 21.09.2026 (баг найден, по прямому указанию — репорт "Нанеси 5 суммарного урона боссам"
// вместо "5 000 000", "Накопи 1 патронов" вместо "1000") — раньше порог парсился регэкспом
// ИЗ САМОЙ check-функции через a.check.toString(). В DEV-сборке это работало (исходный код
// не искажён), но webpack/terser в продовой сборке переписывает круглые числа в экспоненциальную
// запись для экономии байт — 5000000 → "5e6", 1000 → "1e3". Regex \d+ матчит только цифры ДО
// "e", молча обрубая порядок величины: "Урон без границ" (порог 5000000) показывал "5",
// "Закупился на славу" (порог 1000) показывал "1" — и хуже того, РАЗНЫЕ пороги с одинаковой
// первой цифрой (1000/10000/100000/1000000 — все "1e³") давали ОДИНАКОВЫЙ (неверный) результат,
// что ломало ещё и сортировку тиров внутри темы (collapseToTopPerFamily) — с равными "порогами"
// сортировка нестабильна, наверх мог всплыть не настоящий максимальный заработанный тир.
//
// Фикс: threshold теперь ЯВНОЕ поле в каждой записи achievements.js (сгенерировано один раз
// из исходного, ещё не минифицированного текста файла — числа в нём точные), а не выведено из
// рантайм-функции. a.check.toString() остаётся как fallback ТОЛЬКО для записей без explicit
// threshold (не должно происходить для текущих 331 достижений — защита от регресса, если кто-то
// добавит новую запись и забудет threshold).
export function achievementThreshold(a){
    if(typeof a.threshold === 'number') return a.threshold;
    const m = a.check.toString().match(/>=\s*(\d+)/);
    return m ? parseInt(m[1]) : 0;
}

// Ключ темы — для категорий "один пункт = одно самостоятельное достижение" возвращает
// уникальный на каждый id ключ (эффективно НЕ схлопывает).
export function achievementFamilyKey(a){
    if(a.cat === 'kill' || a.cat === 'solo' || a.cat === 'fast'){
        return a.id; // по одному на каждого босса — не тиры, каждый самостоятелен
    }
    if(a.cat === 'zone_clear'){
        // id: zk_<буква локации><порог> — zk_k1, zk_k50, zk_a25... схлопываем по локации.
        const m = a.id.match(/^zk_([a-z])/);
        return 'zone_clear_' + (m ? m[1] : a.id);
    }
    if(a.cat === 'stash'){
        // id: st_<локация>_<тип><1|10> — схлопываем 2 тира одного типа заначки, но не типы между собой.
        const m = a.id.match(/^(st_[a-z]+_[a-z]+)/);
        return m ? m[1] : a.id;
    }
    if(a.cat === 'cards' || a.cat === 'poker' || a.cat === 'roulette'){
        if(/_l\d+$/.test(a.id)) return a.cat + '_level';     // уровни игры — схлопываем
        if(/sp\d+k?$/.test(a.id)) return a.cat + '_spichki'; // спички — схлопываем
        return a.id;                                          // комбинации — каждая своя
    }
    return a.cat; // простые накопительные темы (урон/тушёнка/голоса/опыт и т.д.) — схлопываем целиком
}

// Из списка достижений — по одной на тему: СЛЕДУЮЩИЙ незаработанный тир (та цель, к которой
// игрок сейчас реально идёт), а если тема выполнена полностью — последний (максимальный) тир,
// как финальное состояние. Используется в «Мои достижения».
//
// 25.09.2026 (баг по прямому указанию — "должно быть 50к, а не 10к, ты пишешь достижения,
// которые уже выполнены, а не те, что сейчас выполняются"): раньше здесь показывался МАКСИМАЛЬНЫЙ
// ЗАРАБОТАННЫЙ тир темы (earnedItems[last]) — то есть уже пройденная ступень, а не текущая цель.
// В развёрнутом списке тиров темы (familyMembers, см. svod-achievements.js) этот же заработанный
// тир и так показывается на своём месте — итог: одно и то же достижение дублировалось на экране
// (карточка темы + строка тира), а РЕАЛЬНО актуальная цель (следующий недостигнутый порог) вообще
// не попадала в карточку темы. Теперь карточка темы показывает именно её.
export function collapseToTopPerFamily(list, earned){
    const groups = new Map();
    list.forEach(a => {
        const key = achievementFamilyKey(a);
        if(!groups.has(key)) groups.set(key, []);
        groups.get(key).push(a);
    });

    const out = [];
    groups.forEach(items => {
        items.sort((a, b) => achievementThreshold(a) - achievementThreshold(b));
        const nextUnearned = items.find(a => !earned[a.id]);
        out.push(nextUnearned || items[items.length - 1]);
    });
    return out;
}

// Из списка ТОЛЬКО ЧТО заработанных за один _checkAll() достижений — по одной на тему,
// максимальный порог. Используется в achievements.js, чтобы при одновременном пересечении
// нескольких тиров одной темы (например, потратил разом 1000 энергии и пересёк 3 порога)
// показывался попап только для самого высокого, а не 3 подряд.
export function collapseNewlyEarnedForPopup(newlyEarned){
    const byFamily = new Map();
    newlyEarned.forEach(a => {
        const key = achievementFamilyKey(a);
        const cur = byFamily.get(key);
        if(!cur || achievementThreshold(a) > achievementThreshold(cur)) byFamily.set(key, a);
    });
    return Array.from(byFamily.values());
}

// Все тиры одной темы, по возрастанию порога — используется аккордеоном «Мои достижения»
// (21.09.2026, по прямому указанию: клик по карточке темы разворачивает список ВСЕХ её тиров).
export function familyMembers(list, familyKey){
    return list.filter(a => achievementFamilyKey(a) === familyKey)
        .sort((a, b) => achievementThreshold(a) - achievementThreshold(b));
}

// 21.09.2026 (по прямому указанию, для прогресс-баров тиров в аккордеоне) — читает ТЕКУЩЕЕ
// значение статы достижения из объекта achievements._state() по явному пути statPath (['dmg'],
// ['kills',0], ['stash','k_lezv']). statPath — explicit-поле по ТОЙ ЖЕ логике, что и threshold
// выше (см. коммент там): не завязано на то, манглит ли сборщик имена свойств сейчас — это
// свойство terser НЕ трогает по умолчанию, но явное поле не зависит от этой детали конфигурации.
export function getStatValue(s, statPath){
    let v = s;
    for(const seg of (statPath || [])){
        if(v == null) return 0;
        v = v[seg];
    }
    return v || 0;
}

// Сокращение крупных чисел в игровом стиле — "к" за тысячи, "кк" за миллионы (та же логика,
// что и в id самих достижений: dmg_5kk, auto_1k). Единый источник для описаний достижений
// (interface-achievements.js) и прогресс-баров тиров (svod-achievements.js).
export function formatAchNum(n){
    if(n >= 1000000){
        const v = n / 1000000;
        return (v % 1 === 0 ? v : v.toFixed(1)) + 'кк';
    }
    if(n >= 1000){
        const v = n / 1000;
        return (v % 1 === 0 ? v : v.toFixed(1)) + 'к';
    }
    return String(n);
}
