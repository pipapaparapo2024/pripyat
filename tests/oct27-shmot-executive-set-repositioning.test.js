/**
 * Test: батч правок сета «Исполнительный» и соседних предметов руки (cat:6) — 27.10.2026, по
 * прямому указанию, живые репорты после теста на сервере:
 *  - Бита (id117): позиция/масштаб/поворот иконки в ГАРДЕРОБЕ (не на персонаже) — cellDx/cellDy/
 *    cellScale/cellRot. cellRot — новое поле, раньше вращения у иконок гардероба не было вообще.
 *  - Бита/Худи белая/Худи коричневая: исправлены неверные бонусы (бы ли согласованы между
 *    client/server на неверных числах — не рассинхрон каталогов, просто неверный ввод).
 *  - Сет переименован "Исполнитель" → "Исполнительный" (id116 "Комбинатор" не затронут).
 *  - Часы (Покер, id62) / Цепь (Тинейджер, id92) — репозиция НА ПЕРСОНАЖЕ (manDx/manDy/manScale),
 *    пересчитано от базы MAN_SLOTS cat:6 = (856,418) — та же база, что подтверждена для id117
 *    (745,358 = 856-111,418-60, точное совпадение с ранее продиктованным).
 *  - "фаланги правой руки.png" — уточнена позиция (была приблизительная прикидка, требовавшая
 *    калибровки, см. докблок в коде).
 *  - Дубинка (Зарики, id80) — РЕАЛЬНЫЙ баг (не как с Битой ниже): manDx/manDy вообще не были
 *    заданы, manScale:1.000 на 44×40px "уменьшено"-файле — рендерилась буквально микроскопической.
 *    Пользователь изначально принял её за Биту (внешне спутал на скриншоте) — Бита при проверке
 *    оказалась математически корректной (её калибровка 26.10.2026 сходится без изменений).
 *
 * Run: node tests/oct27-shmot-executive-set-repositioning.test.js
 */
const fs   = require('fs');
const path = require('path');

let passed = 0, failed = 0;
function assert(cond, msg) {
    if (cond) { console.log('  ✅', msg); passed++; }
    else       { console.error('  ❌ FAIL:', msg); failed++; }
}

const root = path.join(__dirname, '..');
const shmotJsSrc = fs.readFileSync(path.join(root, '_client', 'src', 'game', 'shmot.js'), 'utf-8');
const shopSrc    = fs.readFileSync(path.join(root, '_client', 'src', 'game', 'shell', 'overlays', 'shmot_shop.js'), 'utf-8');

console.log('\nTest 1: MAN_SLOTS cat:6 база (856,418) — основа для пересчёта manDx/manDy всех предметов руки ниже');
{
    assert(/\{ cat: 6, x: 856, y: 418 \}/.test(shopSrc), 'база руки (cat:6) в MAN_SLOTS — x:856,y:418 (не менялась)');
    // Регресс-гвард: та же база уже подтверждена точным совпадением для id117 (Бита) —
    // манDx:-111,manDy:-60 → 856-111=745, 418-60=358 — РОВНО продиктованные 26.10.2026 x:745,y:358.
    assert(856 - 111 === 745 && 418 - 60 === 358, 'база (856,418) подтверждена точным совпадением на id117 (sanity)');
}

console.log('\nTest 2: Часы (Покер, id62) — репозиция на персонаже (x:897,y:408,scale:0.880 → manDx:41,manDy:-10)');
{
    assert(856 + 41 === 897 && 418 - 10 === 408, 'арифметика пересчёта manDx/manDy часов сходится (41,-10 → 897,408)');
    assert(/\{id:62, cat:6, name:'Часы \(Покер\)',[^}]*manDx:41, manDy:-10, manScale:0\.880,/.test(shmotJsSrc),
        'id62: manDx:41, manDy:-10, manScale:0.880 записаны в каталог');
}

console.log('\nTest 3: Цепь (Тинейджер, id92) — репозиция на персонаже (x:893,y:406,scale:0.842 → manDx:37,manDy:-12)');
{
    assert(856 + 37 === 893 && 418 - 12 === 406, 'арифметика пересчёта manDx/manDy цепи сходится (37,-12 → 893,406)');
    assert(/\{id:92, cat:6, name:'Цепь \(Тинейджер\)',[^}]*manDx:37, manDy:-12, manScale:0\.842,/.test(shmotJsSrc),
        'id92: manDx:37, manDy:-12, manScale:0.842 записаны в каталог');
}

console.log('\nTest 3b (РЕАЛЬНЫЙ баг, 27.10.2026 — "дубинка на персонаже микроскопическая", изначально спутана с Битой): Дубинка (Зарики, id80) — manDx/manDy не были заданы вообще, manScale:1.000 на 44×40px файле');
{
    // Редактор позиций: x:784,y:349,w:127,h:115 → manDx:-72,manDy:-69 (база 856,418);
    // ПЕРВАЯ калибровка (та же дата) компенсировала недостаточное разрешение файла
    // manScale≈2.880, но позже тем же днём пользователь прислал "натуральный" (не урезанный)
    // исходник 133×121px и попросил выводить ИМЕННО его в натуральном размере — manScale
    // вернулся к 1.000 (файл manImgFile заменён на natural-res копию, manDx/manDy — те же,
    // т.к. оба файла без внутренних отступов, их bbox = весь канвас, см. shmot-man-prescaled-
    // images.test.js).
    assert(856 - 72 === 784 && 418 - 69 === 349, 'арифметика пересчёта manDx/manDy дубинки сходится (-72,-69 → 784,349)');
    assert(/\{id:80, cat:6, name:'Дубинка \(Зарики\)',[^}]*manDx:-72, manDy:-69, manScale:1\.000,/.test(shmotJsSrc),
        'id80: manDx:-72, manDy:-69, manScale:1.000 записаны в каталог (натуральный 133×121px файл вместо урезанного 44×40px)');
}

console.log('\nTest 4: "фаланги правой руки.png" — уточнённая позиция (x:862,y:449,scale:0.789)');
{
    assert(/phalanxSpr\.x = 862;/.test(shopSrc), 'phalanxSpr.x = 862 (было 858, приблизительная прикидка)');
    assert(/phalanxSpr\.y = 449;/.test(shopSrc), 'phalanxSpr.y = 449 (было 425)');
    assert(/phalanxSpr\.scale\.set\(0\.789\);/.test(shopSrc), 'phalanxSpr масштаб 0.789 (было 0.189 — старая прикидка оказалась в ~4 раза меньше нужного)');
}

console.log('\nTest 5 (регресс-гвард — репорт "микроскопическая" изначально спутал Биту с Дубинкой, см. Test 3b выше): Бита (id117) на персонаже НЕ трогалась, её 26.10.2026-калибровка остаётся математически согласованной');
{
    // 26.10.2026: "x:745,y:358,scale:0.210" на ОРИГИНАЛЬНОМ файле (772×634) → 772×0.210≈162,
    // 634×0.210≈133 — РОВНО размер реально сгенерированного manImgFile (подтверждено чтением
    // PNG IHDR обоих файлов на диске и на test-сервере — оба 162×133). Последующая миграция на
    // manImgFile+manScale:1.000 математически ЭКВИВАЛЕНТНА этому же размеру (162×133 — то же
    // самое, что 772×634 при 0.210) — то есть на экране должен быть ТОТ ЖЕ пиксельный размер,
    // что пользователь сам откалибровал и подтвердил 26.10.2026. Код-бага НЕ найдено — возможно,
    // это пересмотр самой калибровки (не баг), либо проблема в чём-то, что эта проверка не
    // покрывает (просьба уточнить номер через редактор позиций, как для часов/цепи выше).
    assert(/\{id:117, cat:6,[^}]*manDx:-111, manDy:-60, manScale:1\.000,/.test(shmotJsSrc),
        'id117: manDx/manDy/manScale НЕ изменены этой правкой (ждут подтверждения/новых чисел)');
}

console.log('\nTest 6: Бита (id117) — иконка гардероба (cellDx/cellDy/cellScale/cellRot) и бонус (+40 к автомату)');
{
    // 27.10.2026: повторное уточнение через редактор позиций (x:225,y:931,scale:0.169,w:131,h:107) —
    // база ячейки (cx+77=229,cy+98=973) выведена из исходной калибровки 25.10.2026, cellRot не менялся.
    assert(/\{id:117, cat:6, name:'Бита \(Исполнительный\)',[^}]*cellDx:-4, cellDy:-42, cellScale:0\.169, cellRot:10,/.test(shmotJsSrc),
        'id117: позиция иконки гардероба (cellDx:-4,cellDy:-42,cellScale:0.169,cellRot:10)');
    assert(/\{id:117, cat:6,[^}]*bonus:'\+40 к автомату',  bk:'auto_flat',     bv:40,/.test(shmotJsSrc),
        'id117: бонус +40 к автомату (была ошибка +250)');
    assert(/if\(item\.cellRot\) img\.rotation = item\.cellRot \* Math\.PI \/ 180;/.test(shopSrc),
        'shmot_shop.js применяет cellRot (новая возможность — вращения иконок гардероба раньше не было)');
}

console.log('\nTest 7: Худи белая (id118, +10 к пистолету) / Худи коричневая (id119, +40 к автомату, была +150 к мачете)');
{
    assert(/\{id:118, cat:1, name:'Худи белая \(Исполнительный\)',[^}]*bonus:'\+10 к пистолету', bk:'gun_flat',      bv:10,/.test(shmotJsSrc),
        'id118: бонус +10 к пистолету (была ошибка +150)');
    assert(/\{id:119, cat:1, name:'Худи коричневая \(Исполнительный\)',[^}]*bonus:'\+40 к автомату',   bk:'auto_flat',  bv:40,/.test(shmotJsSrc),
        'id119: бонус +40 к автомату, тип оружия сменился с мачете на автомат (была +150 к мачете)');
}

console.log('\nTest 8: server/json/shmot_items.json синхронизирован с client shmot.js по всем 3 предметам');
{
    const shmotItems = JSON.parse(fs.readFileSync(path.join(root, 'server', 'json', 'shmot_items.json'), 'utf-8'));
    const expected = { 117: { bk: 'auto_flat', bv: 40 }, 118: { bk: 'gun_flat', bv: 10 }, 119: { bk: 'auto_flat', bv: 40 } };
    for(const id of [117, 118, 119]){
        const item = shmotItems.find(it => it.id === id);
        assert(!!item && item.bk === expected[id].bk && item.bv === expected[id].bv,
            `server shmot_items.json id=${id}: bk=${expected[id].bk}, bv=${expected[id].bv} (получено ${item && item.bk}/${item && item.bv})`);
    }
}

console.log(`\n${'─'.repeat(50)}`);
if (failed === 0) console.log(`✅ All ${passed} tests passed`);
else              { console.log(`❌ ${failed} FAILED, ${passed} passed`); process.exit(1); }
