/**
 * Test: «Панама СССР» (id:24, голова_5.png) на манекене (главный экран/магазин шмоток) сидела
 * на лице, а не на голове — репорт со скриншотом 16.09.2026. Причина: голова_5.png короче
 * (41px) остальных головных уборов (50-58px), а manDy был в том же диапазоне (9), что и у
 * более высоких соседей — предмет садился заметно ниже них. Поднят предварительно на -34px
 * (manDy: 9 → -25), точные координаты — через редактор позиций при необходимости.
 *
 * Run: node tests/panama-sssr-man-offset-fix.test.js
 */

const fs   = require('fs');
const path = require('path');

let passed = 0, failed = 0;
function assert(cond, msg) {
    if (cond) { console.log('  ✅', msg); passed++; }
    else       { console.error('  ❌ FAIL:', msg); failed++; }
}

const src = fs.readFileSync(path.join(__dirname, '..', '_client', 'src', 'game', 'shmot.js'), 'utf-8');

// 18.09.2026: -25 (эта правка) → 15 (см. skill-lvltxt-positions-and-panama-final-manDy.test.js,
// "финальное, подтверждено вживую") → 14 (ещё позже, поднято на 1px по прямой живой правке
// пользователя, см. запись в CLAUDE.md/памяти проекта "shmot.js Панама СССР manDy 15→14").
// 23.09.2026: предмет (id:24 «Панама СССР») УДАЛЁН ЦЕЛИКОМ батчем "убери все шмотки, которые
// покупаются за монеты/тушёнку" — визуально дублировал дроп-вещь «Панама (Охотник)» под другим
// названием/ценой (весь позиционный разбор этого теста стал неактуален вместе с самим
// предметом). Тест теперь — регресс-гвард на то, что id:24 действительно отсутствует.
console.log('\nTest 1: Панама СССР (id:24) удалена батчем 23.09.2026 — позиционные правки этого файла больше не применимы');
{
    const line = src.split('\n').find(l => l.includes("id:24") && l.includes('Панама СССР'));
    assert(!line, 'предмет id:24 «Панама СССР» отсутствует в shmot.js (удалён — дублировал «Панама (Охотник)»)');
}

console.log(`\n${'─'.repeat(50)}`);
if (failed === 0) console.log(`✅ All ${passed} tests passed`);
else              { console.log(`❌ ${failed} FAILED, ${passed} passed`); process.exit(1); }
