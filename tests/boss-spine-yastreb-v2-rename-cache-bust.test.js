const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const source=fs.readFileSync(path.join(root,'_client/src/game/shell/overlays/spine-boss.js'),'utf8');
const atlas='yastreb_v2.atlas', skeleton='yastreb_v4.json';
assert(source.includes(atlas) && source.includes(skeleton));
const dir=path.join(root,'assets/images/spine');
const data=JSON.parse(fs.readFileSync(path.join(dir,skeleton),'utf8'));
assert(data.bones.length>0 && Object.keys(data.animations).length>0);
const pages=fs.readFileSync(path.join(dir,atlas),'utf8').split(/\r?\n/).filter(s=>/\.(png|webp)$/.test(s.trim()));
assert(pages.length>0);for(const page of pages)assert(fs.existsSync(path.join(dir,page.trim())),page);
console.log('Current boss skeleton, binding and atlas textures passed');
