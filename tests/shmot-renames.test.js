/**
 * Test: переименование шмоток, чьё название не совпадало с реальной картинкой
 * (подтверждено пользователем после сверки с изображениями).
 *
 * id13 «Сапоги сталкера» → «Кеды сталкера»          (на картинке кеды, не сапоги)
 * id14 «Антирад-ботинки» → «Кроссы камуфляж»        (на картинке кроссовки-кэмо)
 * id15 «Гравибот «ЦВ»»    → «Кеды чёрные Adidas»     (чёрные кеды Adidas-стиля)
 * id6  «Плащ аномалии»    → «Разгрузка «Я ваша смерть»» (жилет-разгрузка, не плащ)
 * id7  «Экзоскелет»       → «Майка серая»            (обычная серая майка, не броня)
 * id5  «Броня «Свобода»»  — оставлена без изменений (пользователь не возражал)
 *
 * Run: node tests/shmot-renames.test.js
 */

const fs   = require('fs');
const path = require('path');

let passed = 0, failed = 0;
function assert(cond, msg) {
    if (cond) { console.log('  ✅', msg); passed++; }
    else       { console.error('  ❌ FAIL:', msg); failed++; }
}

const shmotSrc = fs.readFileSync(
    path.join(__dirname, '..', '_client', 'src', 'game', 'shmot.js'), 'utf-8'
);

// 23.09.2026 (батч "убери все шмотки, которые не выбиваются с боссов"): id5/6/7/13/14/15 —
// все предметы этого файла — принадлежали удалённому базовому магазину (id0-40), удалены
// целиком. Переименования/id/icon/imgFile разбирать больше не на чем — тест теперь регресс-
// гвард на то, что ни одно из старых ИЛИ новых названий не осталось в файле.
console.log('\nTest 1: все предметы этого файла (id5,6,7,13,14,15) удалены батчем 23.09.2026');
{
    const names = [
        "Кеды сталкера", "Сапоги сталкера",
        "Кроссы камуфляж", "Антирад-ботинки",
        "Кеды чёрные Adidas", "Гравибот «ЦВ»",
        "Разгрузка «Я ваша смерть»", "Плащ аномалии",
        "Майка серая", "Экзоскелет",
        "Броня «Свобода»",
    ];
    for (const name of names) {
        assert(!shmotSrc.includes(`name:'${name}'`), `"${name}" отсутствует в shmot.js`);
    }
}

console.log(`\n${'─'.repeat(50)}`);
if (failed === 0) console.log(`✅ All ${passed} tests passed`);
else              { console.log(`❌ ${failed} FAILED, ${passed} passed`); process.exit(1); }
