/**
 * Test: компас загрузки (#_clo, index.html) когда-то был визуально сжат — оба ассета
 * (компас.png, стрелка компаса.png) на самом деле полноразмерные кадры 1672×941
 * (проверено через PIL), а не квадратные иконки. Фикс на квадратное искажение
 * (aspect-ratio:1672/941 вместо width:25vmin;height:25vmin) был актуален, пока сама
 * картинка компаса существовала.
 *
 * 24.09.2026 (по прямому указанию — "убери с загрузки компас, он не нужен"): картинка
 * компаса со вращающейся стрелкой убрана из index.html целиком. #_clo остался плоским
 * чёрным оверлеем — см. большой комментарий там же (скрывает недогруженную PIXI-сцену,
 * пока не готовы все фоновые модули, не имеет отношения к декоративному компасу).
 *
 * 25.09.2026 (по прямому указанию — "при перелистывании страницы чёрный экран, должен
 * затемняться и показывать загрузку компаса"): компас ВЕРНУЛСЯ, но НЕ в #_clo — новый,
 * отдельный элемент #_screenLoader (полупрозрачный, для переходов между уже загруженными
 * экранами игры, см. tests/screen-transition-compass-loader.test.js) использует новый
 * вплотную обрезанный файл "компас обрезан.png" (не путать со старым "компас.png" —
 * полноразмерный нетронутый кадр 1672×941, который сюда так и не вернулся). Регресс-гвард
 * ниже сужен: проверяет, что КОНКРЕТНО #_clo (первоначальная загрузка) остаётся без
 * компаса — а не что компаса нет во всём файле вообще.
 *
 * Run: node tests/compass-aspect-ratio.test.js
 */

const fs   = require('fs');
const path = require('path');

let passed = 0, failed = 0;
function assert(cond, msg) {
    if (cond) { console.log('  ✅', msg); passed++; }
    else       { console.error('  ❌ FAIL:', msg); failed++; }
}

const html = fs.readFileSync(
    path.join(__dirname, '..', '_client', 'development', 'index.html'), 'utf-8'
);

console.log('\nTest 1: #_clo — плоский чёрный оверлей, без вложенной картинки компаса/стрелки (регресс-гвард)');
{
    assert(/<div id="_clo" style="[^"]*background:#000;[^"]*"><\/div>/.test(html),
        '#_clo — самозакрывающийся div (без вложенных <div> компаса/стрелки внутри)');
    assert(!/aspect-ratio:1672\/941/.test(html), 'старая калибровка aspect-ratio картинки компаса не осталась');
    assert(!/transform-origin:47\.2% 18\.8%/.test(html), 'точка вращения стрелки (pivot) не осталась — стрелки больше нет');
    // 25.09.2026: проверка сужена до КОНКРЕТНО ассетов старого (нетронутого, полноразмерного)
    // компаса — они так и не вернулись. Новый "компас обрезан.png" (см. #_screenLoader,
    // отдельный от #_clo элемент) — легитимное намеренное возвращение декора, не регресс.
    assert(!/[^ ]компас\.png/.test(html) && !html.includes('стрелка компаса.png'),
        'старые ассеты компас.png/стрелка компаса.png (полноразмерные, нетронутые) в разметке не появились — вернулся только новый обрезанный файл');
}

console.log('\nTest 2: #_clo сохранил роль полноэкранного непрозрачного оверлея (не связано с декором компаса)');
{
    assert(/id="_clo" style="[^"]*position:fixed;top:0;left:0;width:100%;height:100%;z-index:9999;/.test(html),
        '#_clo по-прежнему полноэкранный, поверх всего (z-index:9999)');
    assert(/id="_clo" style="[^"]*background:#000;/.test(html), '#_clo по-прежнему полностью непрозрачный чёрный (не полупрозрачный)');
}

console.log(`\n${'─'.repeat(50)}`);
if (failed === 0) console.log(`✅ All ${passed} tests passed`);
else              { console.log(`❌ ${failed} FAILED, ${passed} passed`); process.exit(1); }
