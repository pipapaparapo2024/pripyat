/**
 * Test: 2 бага из скриншотов позиционного редактора.
 *
 * 1) sound.js — бегунок звука/музыки выходил за границы дорожки, потому что TRK_W (368px)
 *    не совпадал с реальной шириной нарисованной дорожки в popup_default.png (~328px,
 *    10 кирпичиков). Каждый шаг громкости (snapVol снапит к 0.1) двигал бегунок на
 *    TRK_W/10=36.8px, хотя реальный кирпичик — только ~32.8px, ошибка копилась на всех
 *    10 шагах и бегунок вылезал за дорожку. Замерено напрямую по пикселям popup_default.png.
 *
 * 2) interface_elements.min.js — кнопка "настройки" (butt_settings) рендерилась как
 *    ПОЛНОЭКРАННЫЙ (1280×720) спрайт вместо иконки-шестерёнки — из-за чего универсальный
 *    редактор позиций (хит-тест по getBounds()) находил при наведении в правом верхнем
 *    углу ХУДа не маленькую иконку, а гигантский на весь экран объект ("кнопка настроек
 *    огромная"). Реальные непрозрачные пиксели иконки внутри картинки — это узкий
 *    прямоугольник 37×35 у правого верхнего угла (bbox замерен через PIL.getbbox()).
 *    Спрайт обрезан текстурной рамкой (PIXI.Rectangle) до этого прямоугольника —
 *    видимая позиция на экране не меняется (x/y сдвинуты на тот же bbox-офсет),
 *    меняются только фактические границы объекта.
 *
 * Run: node tests/sound-popup-track-and-settings-hitbox.test.js
 */

const fs   = require('fs');
const path = require('path');

let passed = 0, failed = 0;
function assert(cond, msg) {
    if (cond) { console.log('  ✅', msg); passed++; }
    else       { console.error('  ❌ FAIL:', msg); failed++; }
}

const soundSrc = fs.readFileSync(
    path.join(__dirname, '..', '_client', 'src', 'game', 'shell', 'popups', 'sound.js'), 'utf-8'
);
const ifaceSrc = fs.readFileSync(
    path.join(__dirname, '..', '_client', 'development', 'libs', 'interface_elements.min.js'), 'utf-8'
);

console.log('\nTest 1: TRK_W дорожки звука уменьшен под реальную ширину рисунка (10 кирпичиков)');
{
    assert(/const TRK_X = 485, TRK_W = 355;/.test(soundSrc),
        'TRK_X/TRK_W заменены на значения из PSD-слоя "шкала" (485, 355), а не старые (471, 368)');
    assert(!/const TRK_X = 471, TRK_W = 368;/.test(soundSrc), 'старые ошибочные значения убраны');
}

console.log('\nTest 2: butt_settings обрезан текстурной рамкой вместо полноэкранного 1280×720 спрайта');
{
    assert(!/_bst\.width=1280;_bst\.height=720;_bst\.x=20;/.test(ifaceSrc),
        'старый полноэкранный спрайт (1280×720) убран');
    // 25.09.2026 (по прямому указанию, новый файл пользователя — "кнопка настройки.png"):
    // butt_settings.png на сервере ЗАМЕНЁН на новый, уже вплотную обрезанный файл (37×35,
    // 1-в-1 размер старого bbox-выреза) — вырез больше не нужен со смещением (1217,21) на
    // старый большой холст, сдвинут на (0,0) — берёт новый маленький файл целиком. Видимая
    // экранная позиция иконки (_bst.x/_bst.y) при этой правке не менялась — только откуда
    // вырезаются пиксели внутри текстуры (Y уточнён ОТДЕЛЬНОЙ правкой тем же днём, см. ниже).
    assert(/new PIXI\.Texture\(m\.baseTexture,new PIXI\.Rectangle\(0,0,37,35\)\)/.test(ifaceSrc),
        'текстура обрезана рамкой 0,0,37,35 (новый файл уже вплотную обрезан, смещение не нужно)');
    assert(!/new PIXI\.Texture\(m\.baseTexture,new PIXI\.Rectangle\(1217,21,37,35\)\)/.test(ifaceSrc),
        'старое смещение (1217,21) для прежнего большого холста убрано');
    // 25.09.2026 (повторная правка тем же днём, редактор позиций — "x:1237 y:23 scale:1.000"):
    // Y уточнён с 21 на 23, хитбокс сведён к той же позиции — см.
    // tests/settings-hitbox-and-super-copy-button.test.js для полной проверки этой правки.
    assert(/_bst\.x=1237;_bst\.y=23;/.test(ifaceSrc),
        'экранная позиция иконки уточнена редактором позиций (1237,23)');
}

console.log(`\n${'─'.repeat(50)}`);
if (failed === 0) console.log(`✅ All ${passed} tests passed`);
else              { console.log(`❌ ${failed} FAILED, ${passed} passed`); process.exit(1); }
