/**
 * Test: батч 25.09.2026 (по прямому указанию, ~58 предметов боссовых сетов, "именно в
 * ячейках") — позиция/масштаб иконки предмета ВНУТРИ ячейки магазина шмоток (shmot_shop.js
 * _shopRefresh), а НЕ позиция на экипированном персонаже (это manDx/manDy/manScale, отдельные
 * поля, не трогались).
 *
 * Раньше ВСЕ предметы центрировались в ячейке одной формулой (cx+77, cy+98) с авто-fit
 * масштабом (только уменьшал, никогда не увеличивал). Новые поля cellDx/cellDy/cellScale —
 * точные поправки НА КОНКРЕТНЫЙ ПРЕДМЕТ относительно той же формулы (77,98) — координаты,
 * снятые пользователем через редактор позиций, переведены в дельту от генерик-формулы через
 * привязку к сетке (colStep=145+12=157, rowStep=160+12=172, см. shmot_shop.js GRID) — это
 * позволяет применить дельту КОРРЕКТНО независимо от того, в какой именно ячейке (столбец/
 * строка) предмет физически оказался при показе (зависит от того, что игрок уже владеет/от
 * категории) — что и означает "по пропорциям", как явно попросил пользователь для шорт/обуви/
 * предметов в руку без явных координат (применить ту же дельту, что у эталонного предмета
 * категории, а не тот же абсолютный пиксель).
 *
 * Run: node tests/shmot-cell-icon-positions-batch.test.js
 */

const fs   = require('fs');
const path = require('path');

let passed = 0, failed = 0;
function assert(cond, msg) {
    if (cond) { console.log('  ✅', msg); passed++; }
    else       { console.error('  ❌ FAIL:', msg); failed++; }
}

const root = path.join(__dirname, '..');
const shmotSrc = fs.readFileSync(path.join(root, '_client', 'src', 'game', 'shmot.js'), 'utf-8');
const shopSrc  = fs.readFileSync(path.join(root, '_client', 'src', 'game', 'shell', 'overlays', 'shmot_shop.js'), 'utf-8');

