console.log('\nTest 1: все 58 предметов boss-сетов (id41-99, cat 0/1/2/3/6) получили cellDx/cellDy/cellScale');
{
    const ids = Object.keys(CELLS);
    assert(ids.length === 58, 'таблица покрывает ровно 58 предметов (11 голова + 12 торс + 12 шорты + 11 обувь + 12 в руку)');
    let ok = 0;
    ids.forEach(id => {
        const [dx, dy, sc] = CELLS[id];
        // 25.09.2026: масштаб в файле записан то с 3 знаками после запятой (0.150), то без
        // хвостовых нулей (0.79, 0.22) — зависит от того, каким скриптом писался конкретный
        // батч. Принимаем оба варианта записи одного и того же числа, не гадаем какой формат
        // выбрать для каждого id по отдельности.
        const scVariants = Array.from(new Set([sc.toFixed(3), String(sc)])).map(v => v.replace('.', '\\.'));
        const re = new RegExp('\\{id:' + id + ', cat:\\d, name:\'[^\']*\',[^\\n]*?imgFile:\'[^\']*\', cellDx:' +
            dx + ', cellDy:' + dy + ', cellScale:(?:' + scVariants.join('|') + '),');
        if(re.test(shmotSrc)) ok++;
        else console.error('    ✗ id ' + id + ' — не найдено cellDx:' + dx + ', cellDy:' + dy + ', cellScale:' + sc);
    });
    assert(ok === ids.length, 'все ' + ids.length + ' записей применены корректно (найдено ' + ok + ')');
}

console.log('\nTest 2: явно заданные предметы (шапки/торс) — контрольная сверка по нескольким id, снятым напрямую');
{
    assert(/\{id:41, cat:0, name:'Панама \(Охотник\)',[^\n]*?cellDx:-3, cellDy:-30, cellScale:0\.277,/.test(shmotSrc),
        'id41 Панама (Охотник) — x:74,y:68,scale:0.277 → dx:-3,dy:-30 (col0,row0)');
    assert(/\{id:55, cat:1, name:'Майка \(Баркут\)',[^\n]*?cellDx:0, cellDy:-32, cellScale:0\.661,/.test(shmotSrc),
        'id55 Майка (Баркут) — x:77,y:238,scale:0.661 (в ячейке, НЕ путать с manDx:1/manDy:4 — позиция на персонаже, другое поле)');
    assert(/\{id:64, cat:0, name:'Бандана \(Зарики\)',[^\n]*?cellDx:-2, cellDy:-29, cellScale:1\.000,/.test(shmotSrc),
        'id64 Бандана (Зарики) — x:232,y:241,scale:1.000 (единственный предмет без уменьшения — нативный размер файла подходит)');
}

console.log('\nTest 3: "по пропорциям" — оставшиеся шорты/обувь/предметы в руку получили ТУ ЖЕ дельту, что и эталонный предмет категории');
