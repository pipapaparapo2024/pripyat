const assert=require('node:assert/strict');
const fs=require('node:fs');
const {execFileSync}=require('node:child_process');
const {findPhpBin}=require('./_php_bin.js');
const php=findPhpBin();
if(!php)throw new Error('Для проверки закрытого Telegram-входа требуется PHP');
process.stdout.write(execFileSync(php,['tests/_php_fixtures/telegram-website-test-access.php'],{encoding:'utf8'}));
const auth=fs.readFileSync('website/app/auth.php','utf8');
const nginx=fs.readFileSync('tools/deploy-website-telegram-auth-test.py','utf8');
const login=fs.readFileSync('website/telegram-login-test.js','utf8');
assert.match(auth,/TelegramWebsiteTestAccess::redeem/);
assert.match(auth,/telegram_test_access_required/);
assert.match(auth,/websiteAuthDiagnostic\('rejected',\$stage,\$e\)/);
assert.match(auth,/websiteAuthDiagnostic\('failed',\$stage,\$e\)/);
assert.match(auth,/website-auth-diagnostics\.log/);
assert.match(auth,/invalid_jwt_signature/);
assert.doesNotMatch(auth,/error_log\([^\n]*(?:\$code|\$state|id_token|claims)/);
assert.match(auth,/providers'=>\['telegram'=>\(bool\)\(\$ready&&\$preview\)\]/);
assert.match(nginx,/status\|test-access\|bootstrap\|logout\|start\|callback/);
assert.match(nginx,/access_log off/);
assert.match(nginx,/Referrer-Policy no-referrer/);
assert.match(login,/location\.hash\.slice\(1\)/);
assert.match(login,/history\.replaceState\(null,'',location\.pathname\+location\.search\)/);
assert.match(login,/auth\/telegram\/test-access/);
assert.doesNotMatch(login,/localStorage|sessionStorage/);
console.log('Telegram website login: preview gate, HTTP routes and fragment cleanup checked');
