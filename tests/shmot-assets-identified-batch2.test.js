/**
 * Test: батч 18-19.09.2026 — второй раунд сопоставления файлов из папки "шмотки" (исходники
 * художника) с реальными предметами из Шмот.docx. Первый раунд (панама ссср, серп, молот,
 * мачете, бита, кукла вуду и т.д.) подтверждён отдельно в переписке ранее и уже скопирован
 * в _client/development/images/ под старыми проверками — этот файл фиксирует ВТОРОЙ раунд,
 * подтверждённый пользователем явно по каждому файлу (не угадан):
 *
 *  - 1.png              → Кроссовки +10 к мачете     (сет «спортик 2.0»)
 *  - Слой 17.png         → Кепка +80 к автомату       (Меченный, сет «вольный»)
 *  - Слой 18.png         → Кроссовки +80 к автомату   (Соло Меченный, сет «вольный»)
 *  - Слой 30.png         → Шорты +30 к пистолету      (сет «Игроман 2.0», с зариков)
 *  - Слой 43 копия.png   → Кроссовки +20 к мачете     (сет «Игроман 2.0», с зариков)
 *  - Слой 47.png         → Кроссовки +120 к автомату  (Баркут, сет «спортик»)
 *  - бандана.png (НЕ бандана-1.png) → Бандана +50 к автомату (сет «Игроман 2.0», с зариков)
 *
 * ВАЖНО: "Слой 18.png" (обувь Меченного) заменяет более раннюю ДОГАДКУ "Слой 7.png" для того
 * же слота — та догадка не была подтверждена пользователем и не должна использоваться.
 *
 * Это только каталогизация ассетов (переименованы и скопированы в _client/development/images/,
 * без стретчинга — исходники остаются в родном разрешении, см. preview 150px, отправленный
 * пользователю). Wiring в shmot.js (реальные записи предметов/бонусов/тултипов) — отдельная,
 * ещё не начатая задача, т.к. каталог shmot.js сейчас не соответствует сетам из Шмот.docx.
 *
 * Run: node tests/shmot-assets-identified-batch2.test.js
 */

const fs   = require('fs');
const path = require('path');

let passed = 0, failed = 0;
function assert(cond, msg) {
    if (cond) { console.log('  ✅', msg); passed++; }
    else       { console.error('  ❌ FAIL:', msg); failed++; }
}

const IMAGES_DIR = path.join(__dirname, '..', '_client', 'development', 'images');

const CONFIRMED_BATCH2 = [
    { file: 'шмот кроссовки спортик2.0.png', item: 'Кроссовки +10 к мачете',    set: 'спортик 2.0' },
    { file: 'шмот кепка вольный.png',        item: 'Кепка +80 к автомату',      set: 'вольный (Меченный)' },
    { file: 'шмот кроссовки вольный.png',    item: 'Кроссовки +80 к автомату',  set: 'вольный (Соло Меченный)' },
    { file: 'шмот шорты игроман2.0.png',     item: 'Шорты +30 к пистолету',     set: 'Игроман 2.0 (зарики)' },
    { file: 'шмот кроссовки игроман2.0.png', item: 'Кроссовки +20 к мачете',    set: 'Игроман 2.0 (зарики)' },
    { file: 'шмот кроссовки спортик.png',    item: 'Кроссовки +120 к автомату', set: 'спортик (Баркут)' },
    // 29.09.2026 (найдено плановой чисткой при не связанной правке): имя файла в shmot.js
    // (imgFile, id:64) — "шмот бандана игроман2.0 зарики.png" (с суффиксом " зарики"), этот
    // тест годами ждал имя без суффикса, которого на диске никогда не было.
    { file: 'шмот бандана игроман2.0 зарики.png', item: 'Бандана +50 к автомату', set: 'Игроман 2.0 (зарики)' },
];

console.log('\nTest 1: все 7 подтверждённых файлов второго раунда лежат в _client/development/images/shmot/');
console.log('(19.09.2026: были ошибочно скопированы в корень images/ — код (home.js/shmot_shop.js)');
console.log('грузит их из images/shmot/, из-за чего все были 404 на живом сайте, см. shmot-organized-catalog-and-sources.test.js)');
{
    for (const { file, item, set } of CONFIRMED_BATCH2) {
        assert(fs.existsSync(path.join(IMAGES_DIR, 'shmot', file)), `${file} — "${item}" (${set})`);
    }
}

console.log('\nTest 2: файлы не пустые и не повреждены (валидный PNG-заголовок)');
{
    for (const { file } of CONFIRMED_BATCH2) {
        const full = path.join(IMAGES_DIR, 'shmot', file);
        if (!fs.existsSync(full)) continue;
        const buf = fs.readFileSync(full);
        const isPng = buf.length > 8 && buf[0] === 0x89 && buf[1] === 0x50 && buf[2] === 0x4E && buf[3] === 0x47;
        assert(isPng, `${file} — валидный PNG-заголовок, размер ${buf.length} байт`);
    }
}

console.log('\nTest 3: старая непроверенная догадка ("Слой 7.png" = обувь Меченного) НЕ используется как имя файла в проекте');
{
    // "Слой 18.png" (переименован в "шмот кроссовки вольный.png") — подтверждённый пользователем
    // файл для этого слота, "Слой 7.png" был лишь моей неподтверждённой догадкой и не должен
    // был попасть в проект под этим именем предмета.
    const wrongGuessPath = path.join(IMAGES_DIR, 'шмот кроссовки вольный (Слой 7).png');
    assert(!fs.existsSync(wrongGuessPath), 'неподтверждённая догадка не скопирована в проект под этим именем');
}

console.log(`\n${'─'.repeat(50)}`);
if (failed === 0) console.log(`✅ All ${passed} tests passed`);
else              { console.log(`❌ ${failed} FAILED, ${passed} passed`); process.exit(1); }
